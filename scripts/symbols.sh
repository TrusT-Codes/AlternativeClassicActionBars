#!/usr/bin/env bash
# Writes docs/symbols.txt: "File.lua:line  ACAB:Method" for every ACAB method/field function
# and every *Mixin method, files in .toc order. Generated, grep-only; never edit by hand.
# Usage: scripts/symbols.sh [repoRoot]
set -e
ROOT="$(cd "${1:-$(dirname "$0")/..}" && pwd)"
cd "$ROOT"
FILES=$(grep -E '^[A-Za-z].*\.lua' AlternativeClassicActionBars.toc | tr -d '\r')
{
  echo "# Generated by scripts/symbols.sh (run by verify.sh). Grep it, never read it whole."
  for f in $FILES; do
    awk -v file="$f" '
      { sub(/\r$/, "") }
      match($0, /^[ \t]*function (ACAB|[A-Za-z_]+Mixin)[:.][A-Za-z_][A-Za-z0-9_]*/) {
        s = substr($0, RSTART, RLENGTH); sub(/^[ \t]*function /, "", s)
        printf "%s:%d  %s\n", file, FNR, s; next
      }
      match($0, /^[ \t]*(ACAB|[A-Za-z_]+Mixin)\.[A-Za-z_][A-Za-z0-9_]*[ \t]*=[ \t]*function/) {
        s = substr($0, RSTART, RLENGTH); sub(/^[ \t]*/, "", s); sub(/[ \t]*=.*/, "", s)
        printf "%s:%d  %s\n", file, FNR, s
      }
    ' "$f"
  done
} > docs/symbols.txt
echo "symbols: $(($(wc -l < docs/symbols.txt) - 1)) entries -> docs/symbols.txt"
